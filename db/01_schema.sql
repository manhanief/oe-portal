-- Run as RESTO in FREEPDB1
-- Restaurant ordering system schema. Safe to re-run: drops and recreates all tables.

WHENEVER SQLERROR EXIT FAILURE ROLLBACK

-- Drop in child-to-parent order
DROP TABLE IF EXISTS order_items       CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS orders            CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS menu_items        CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS categories        CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS restaurant_tables CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS users             CASCADE CONSTRAINTS PURGE;

-- ---------------------------------------------------------------
-- CATEGORIES
-- ---------------------------------------------------------------
CREATE TABLE categories (
  category_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  name         VARCHAR2(50)  NOT NULL,
  sort_order   NUMBER(3)     DEFAULT 0 NOT NULL,
  is_active    NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT pk_categories        PRIMARY KEY (category_id),
  CONSTRAINT uq_categories_name   UNIQUE (name),
  CONSTRAINT ck_categories_active CHECK (is_active IN (0, 1))
);

-- ---------------------------------------------------------------
-- MENU_ITEMS
-- ---------------------------------------------------------------
CREATE TABLE menu_items (
  item_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  category_id   NUMBER         NOT NULL,
  name          VARCHAR2(100)  NOT NULL,
  description   VARCHAR2(500),
  price         NUMBER(8, 2)   NOT NULL,
  image_url     VARCHAR2(500),
  is_available  NUMBER(1)      DEFAULT 1 NOT NULL,
  CONSTRAINT pk_menu_items           PRIMARY KEY (item_id),
  CONSTRAINT fk_menu_items_category  FOREIGN KEY (category_id) REFERENCES categories (category_id),
  CONSTRAINT uq_menu_items_name      UNIQUE (name),
  CONSTRAINT ck_menu_items_price     CHECK (price >= 0),
  CONSTRAINT ck_menu_items_available CHECK (is_available IN (0, 1))
);

-- ---------------------------------------------------------------
-- RESTAURANT_TABLES
-- ---------------------------------------------------------------
CREATE TABLE restaurant_tables (
  table_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  table_no  VARCHAR2(10) NOT NULL,
  seats     NUMBER(2)    NOT NULL,
  CONSTRAINT pk_restaurant_tables PRIMARY KEY (table_id),
  CONSTRAINT uq_restaurant_tables UNIQUE (table_no),
  CONSTRAINT ck_restaurant_seats  CHECK (seats > 0)
);

-- ---------------------------------------------------------------
-- ORDERS
-- ---------------------------------------------------------------
CREATE TABLE orders (
  order_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  order_no       VARCHAR2(20)   NOT NULL,
  table_id       NUMBER,
  order_type     VARCHAR2(10)   NOT NULL,
  customer_name  VARCHAR2(100),
  status         VARCHAR2(12)   DEFAULT 'PENDING' NOT NULL,
  subtotal       NUMBER(10, 2)  NOT NULL,
  tax            NUMBER(10, 2)  DEFAULT 0 NOT NULL,
  total          NUMBER(10, 2)  NOT NULL,
  created_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_orders          PRIMARY KEY (order_id),
  CONSTRAINT uq_orders_no       UNIQUE (order_no),
  CONSTRAINT fk_orders_table    FOREIGN KEY (table_id) REFERENCES restaurant_tables (table_id),
  CONSTRAINT ck_orders_type     CHECK (order_type IN ('DINE_IN', 'TAKEAWAY')),
  CONSTRAINT ck_orders_status   CHECK (status IN ('PENDING', 'PREPARING', 'READY', 'COMPLETED', 'CANCELLED')),
  CONSTRAINT ck_orders_amounts  CHECK (subtotal >= 0 AND tax >= 0 AND total >= 0),
  -- Dine-in must have a table; takeaway must not
  CONSTRAINT ck_orders_table_by_type CHECK (
       (order_type = 'DINE_IN'  AND table_id IS NOT NULL)
    OR (order_type = 'TAKEAWAY' AND table_id IS NULL)
  )
);

-- ---------------------------------------------------------------
-- ORDER_ITEMS
-- ---------------------------------------------------------------
CREATE TABLE order_items (
  order_item_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  order_id       NUMBER         NOT NULL,
  item_id        NUMBER         NOT NULL,
  quantity       NUMBER(3)      NOT NULL,
  unit_price     NUMBER(8, 2)   NOT NULL,  -- price at the time of ordering
  notes          VARCHAR2(200),
  CONSTRAINT pk_order_items       PRIMARY KEY (order_item_id),
  CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (order_id) ON DELETE CASCADE,
  CONSTRAINT fk_order_items_item  FOREIGN KEY (item_id)  REFERENCES menu_items (item_id),
  CONSTRAINT ck_order_items_qty   CHECK (quantity > 0),
  CONSTRAINT ck_order_items_price CHECK (unit_price >= 0)
);

-- ---------------------------------------------------------------
-- USERS (staff and admin only; customers do not log in)
-- ---------------------------------------------------------------
CREATE TABLE users (
  user_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  username       VARCHAR2(50)   NOT NULL,
  password_hash  VARCHAR2(200)  NOT NULL,
  role           VARCHAR2(10)   NOT NULL,
  CONSTRAINT pk_users          PRIMARY KEY (user_id),
  CONSTRAINT uq_users_username UNIQUE (username),
  CONSTRAINT ck_users_role     CHECK (role IN ('ADMIN', 'STAFF'))
);

-- ---------------------------------------------------------------
-- Indexes on foreign keys and common filters
-- (Oracle does not index foreign key columns automatically)
-- ---------------------------------------------------------------
CREATE INDEX ix_menu_items_category  ON menu_items (category_id);
CREATE INDEX ix_orders_table         ON orders (table_id);
CREATE INDEX ix_orders_status_date   ON orders (status, created_at);
CREATE INDEX ix_order_items_order    ON order_items (order_id);
CREATE INDEX ix_order_items_item     ON order_items (item_id);

PROMPT Schema created.
EXIT
